export function normalizeLocalePreference(value: unknown): LocalePreference {
  return value === "en" || value === "fa" || value === "auto"
    ? value
    : "auto";
}

export function detectLocale(languages: readonly string[] = browserLanguages()): ResolvedLocale {
  return languages.some((language) => language.toLowerCase().startsWith("fa"))
    ? "fa"
    : "en";
}

export function applyWebLocale(value: unknown): void {
  const preference = normalizeLocalePreference(value);
  const resolved = preference === "auto" ? detectLocale() : preference;
  localePreference.value = preference;
  resolvedLocale.value = resolved;

  const root = document.documentElement;
  root.lang = resolved === "fa" ? "fa-IR" : "en";
  root.dir = resolved === "fa" ? "rtl" : "ltr";
  root.dataset.locale = preference;
  root.dataset.resolvedLocale = resolved;
  document.title = t("PCController");
  document
    .querySelector('meta[name="description"]')
    ?.setAttribute(
      "content",
      t("Private local control surface for PCController")
    );
  document
    .querySelector('meta[name="application-name"]')
    ?.setAttribute("content", t("PCController"));
  document
    .querySelector('meta[name="apple-mobile-web-app-title"]')
    ?.setAttribute("content", t("PCController"));
  try {
    window.localStorage.setItem(STORAGE_KEY, preference);
  } catch {
    // Configuration remains authoritative if storage is unavailable.
  }
}

export function startWebLocaleController(): () => void {
  const onLanguageChange = () => {
    if (localePreference.value === "auto") applyWebLocale("auto");
  };
  window.addEventListener("languagechange", onLanguageChange);
  return () => window.removeEventListener("languagechange", onLanguageChange);
}

export function t(
  source: string,
  values?: Readonly<Record<string, string | number>>
): string {
  const translated = resolvedLocale.value === "fa" ? fa[source] ?? source : source;
  if (!values) return translated;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

export function formatNumber(
  value: number,
  options?: Intl.NumberFormatOptions
): string {
  return new Intl.NumberFormat(localeTag(), {
    numberingSystem: resolvedLocale.value === "fa" ? "arabext" : "latn",
    ...options
  }).format(value);
}

export function formatDateTime(
  value: Date | number,
  options: Intl.DateTimeFormatOptions
): string {
  return new Intl.DateTimeFormat(localeTag(), {
    calendar: resolvedLocale.value === "fa" ? "persian" : "gregory",
    numberingSystem: resolvedLocale.value === "fa" ? "arabext" : "latn",
    ...options
  }).format(value);
}

export function localizeDigits(value: string | number): string {
  const text = String(value);
  if (resolvedLocale.value !== "fa") return text;
  return text.replace(/\d/g, (digit) => PERSIAN_DIGITS[ASCII_DIGITS.indexOf(digit)]);
}

export function BidiLtr({
  children,
  class: className = ""
}: {
  children: ComponentChildren;
  class?: string;
}) {
  return (
    <bdi dir="ltr" class={`bidi-ltr ${className}`.trim()}>
      {children}
    </bdi>
  );
}

function localeTag(): string {
  return resolvedLocale.value === "fa" ? "fa-IR" : "en-US";
}

function browserLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return ["en"];
  return navigator.languages?.length
    ? navigator.languages
    : [navigator.language || "en"];
}
